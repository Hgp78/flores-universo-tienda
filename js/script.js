function applyLanguage(lang) {
  const t = translations[lang] || translations.es;
  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    if (t[key] !== undefined) {
      el.innerHTML = t[key];
    }
  });

  const currentLanguage = document.querySelector("#currentLanguage");
  if (currentLanguage) currentLanguage.textContent = t.code;

  localStorage.setItem("floresUniverseLanguage", lang);
}

document.querySelectorAll(".buy").forEach((button) => {
  button.addEventListener("click", (event) => {
    const url = payhipLinks[button.dataset.product];
    if (!url) {
      event.preventDefault();
      alert("No se encontró el enlace de compra.");
      return;
    }
    button.href = url;
  });
});

const langButton = document.querySelector(".language-button");
const langMenu = document.querySelector("#languageMenu");

langButton?.addEventListener("click", () => {
  const open = langMenu.classList.toggle("open");
  langButton.setAttribute("aria-expanded", String(open));
});

document.querySelectorAll("#languageMenu [data-lang]").forEach((option) => {
  option.addEventListener("click", () => {
    applyLanguage(option.dataset.lang);
    langMenu.classList.remove("open");
    langButton.setAttribute("aria-expanded", "false");
  });
});

document.addEventListener("click", (event) => {
  if (!event.target.closest(".language-picker")) {
    langMenu?.classList.remove("open");
    langButton?.setAttribute("aria-expanded", "false");
  }
});

